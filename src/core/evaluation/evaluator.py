    # =========================================================================
    # SAVE RESULTS
    # =========================================================================

    def _save_results(
        self,
        outer_results: pd.DataFrame,
        inner_candidates: pd.DataFrame,
        oof_predictions: pd.DataFrame,
        repeat_metrics: pd.DataFrame,
        summary: pd.DataFrame,
        selection_frequency: pd.DataFrame,
        final_selection: dict,
        final_candidates: pd.DataFrame,
    ) -> None:
        """
        Save raw model-selection outputs.

        Plotting/reporting is intentionally handled elsewhere.
        """

        os.makedirs(
            self.output_dir,
            exist_ok=True,
        )

        outputs = {
            "outer_fold_results.csv":
                outer_results,

            "inner_candidate_results.csv":
                inner_candidates,

            "oof_predictions.csv":
                oof_predictions,

            "repeat_metrics.csv":
                repeat_metrics,

            "eval_summary.csv":
                summary,

            "selection_frequency.csv":
                selection_frequency,

            "final_candidate_results.csv":
                final_candidates,
        }

        for filename, dataframe in (
            outputs.items()
        ):

            dataframe.to_csv(
                os.path.join(
                    self.output_dir,
                    filename,
                ),
                index=False,
            )

        with open(
            os.path.join(
                self.output_dir,
                "final_selection.json",
            ),
            "w",
            encoding="utf-8",
        ) as file:

            json.dump(
                final_selection,
                file,
                indent=2,
            )

        logger.info(
            "Evaluation results saved to %s",
            self.output_dir,
        )

    # =========================================================================
    # RANDOM SEEDS
    # =========================================================================

    def _outer_seed(
        self,
        outer_repeat: int,
    ) -> int:
        return (
            self.random_state
            + outer_repeat
        )

    def _inner_seed(
        self,
        outer_repeat: int,
        outer_fold: int,
    ) -> int:
        return (
            self.random_state
            + 1_000
            + 100 * outer_repeat
            + outer_fold
        )

    def _optuna_seed(
        self,
        model_enum: RegressionModels,
        outer_repeat: int,
        outer_fold: int,
    ) -> int:
        return (
            self.random_state
            + 40_000
            + 10_000 * outer_repeat
            + 100 * outer_fold
            + model_enum.value
        )
