# =============================================================================
# DATA STRUCTURES
# =============================================================================


@dataclass(frozen=True)
class RegressionMetrics:
    mae: float
    rmse: float
    r2: float


@dataclass(frozen=True)
class InnerSplit:
    train_bags: tuple
    validation_bags: tuple


@dataclass
class PreparedInnerFold:
    df_validation: pd.DataFrame
    X_train: pd.DataFrame
    y_train: pd.DataFrame
    X_validation: pd.DataFrame
    weights: np.ndarray
    processor: PostSplitProcessor


# =============================================================================
# MODEL EVALUATOR
# =============================================================================


class ModelEvaluator:
    """
    Nested grouped cross-validation for complete ML-pipeline selection.

    Selection hierarchy
    -------------------
    For each outer fold:

        outer training Points
            ->
        inner grouped CV
            ->
        optimize each model family independently
            ->
        compare each family's best inner-CV MAE
            ->
        select one complete pipeline
            ->
        refit on all outer-training data
            ->
        evaluate once on outer-test Points

    The complete pipeline includes:

        model family
        feature set
        aggregation strategy
        dimensionality reduction
        PCA dimensionality
        model hyperparameters

    Mean and median predictors are evaluated as training-only baselines
    but never participate in pipeline selection.

    All train/test splitting is grouped by Point.
    """

    def __init__(
        self,
        schema: Schema,
        output_dir: str,
        models: list[RegressionModels],
        random_state: int,
        feature_sets: tuple[str, ...],
        aggregations: tuple[str, ...],
        reductions: tuple[str, ...],
        pca_indices_candidates: tuple[int, ...],
        pca_embeddings_candidates: tuple[int, ...],
        outer_splits: int,
        outer_repeats: int,
        inner_splits: int,
        optuna_trials: int,
    ) -> None:

        self.schema = schema
        self.output_dir = output_dir

        self.models = models
        self.random_state = random_state

        self.feature_sets = feature_sets
        self.aggregations = aggregations
        self.reductions = reductions

        self.pca_indices_candidates = (
            pca_indices_candidates
        )

        self.pca_embeddings_candidates = (
            pca_embeddings_candidates
        )

        self.outer_splits = outer_splits
        self.outer_repeats = outer_repeats
        self.inner_splits = inner_splits
        self.optuna_trials = optuna_trials

    # =========================================================================
    # PUBLIC API
    # =========================================================================

    def evaluate(
        self,
        signatures: dict[str, pd.DataFrame],
    ) -> None:
        """
        Evaluate complete pipeline selection with repeated nested grouped CV.

        Parameters
        ----------
        signatures : dict[str, pd.DataFrame]
            CapturePointId-level representations generated by
            PreSplitProcessor.process_all().

            Expected structure:

                {
                    "mean": ...,
                    "mean_std": ...,
                    "hierarchical": ...,
                }
        """

        self._check_signature_alignment(
            signatures
        )

        reference = signatures[
            self.aggregations[0]
        ]

        feature_dimensions = (
            self._feature_dimensions(
                signatures
            )
        )

        logger.info(
            "Starting nested pipeline selection: "
            "%d CapturePointIds, %d Points, "
            "%d outer repeats x %d folds",
            len(reference),
            reference[
                self.schema.group
            ].nunique(),
            self.outer_repeats,
            self.outer_splits,
        )

        outer_rows: list[dict] = []
        candidate_rows: list[dict] = []
        prediction_rows: list[pd.DataFrame] = []

        # =====================================================================
        # REPEATED OUTER CV
        # =====================================================================

        for outer_repeat in range(
            1,
            self.outer_repeats + 1,
        ):

            outer_cv = GroupKFold(
                n_splits=self.outer_splits,
                shuffle=True,
                random_state=self._outer_seed(
                    outer_repeat
                ),
            )

            groups = reference[
                self.schema.group
            ].to_numpy()

            for outer_fold, (
                train_idx,
                test_idx,
            ) in enumerate(
                outer_cv.split(
                    reference,
                    groups=groups,
                ),
                start=1,
            ):

                logger.info(
                    "Outer repeat %d/%d — fold %d/%d",
                    outer_repeat,
                    self.outer_repeats,
                    outer_fold,
                    self.outer_splits,
                )

                df_train_reference = (
                    reference.iloc[
                        train_idx
                    ]
                )

                df_test_reference = (
                    reference.iloc[
                        test_idx
                    ]
                )

                train_bags = tuple(
                    df_train_reference[
                        self.schema.bag
                    ].tolist()
                )

                test_bags = tuple(
                    df_test_reference[
                        self.schema.bag
                    ].tolist()
                )

                # -------------------------------------------------------------
                # Create inner splits once and reuse them for every model family
                # and every Optuna trial.
                # -------------------------------------------------------------

                inner_splits = (
                    self._make_inner_splits(
                        df_train_reference,
                        outer_repeat=outer_repeat,
                        outer_fold=outer_fold,
                    )
                )

                min_inner_train_size = min(
                    len(
                        split.train_bags
                    )
                    for split in inner_splits
                )

                # -------------------------------------------------------------
                # Preprocessing cache is shared across model families.
                #
                # If two trials use the same representation configuration,
                # scaling/PCA need not be fitted again.
                # -------------------------------------------------------------

                preprocessing_cache: dict[
                    tuple,
                    list[PreparedInnerFold],
                ] = {}

                family_results = []

                # =============================================================
                # INNER MODEL-FAMILY OPTIMIZATION
                # =============================================================

                for model_enum in self.models:

                    result = (
                        self._optimize_family(
                            model_enum=model_enum,
                            signatures=signatures,
                            train_bags=train_bags,
                            inner_splits=inner_splits,
                            feature_dimensions=(
                                feature_dimensions
                            ),
                            min_inner_train_size=(
                                min_inner_train_size
                            ),
                            preprocessing_cache=(
                                preprocessing_cache
                            ),
                            outer_repeat=outer_repeat,
                            outer_fold=outer_fold,
                        )
                    )

                    family_results.append(
                        result
                    )

                    candidate_rows.append(
                        {
                            "outer_repeat":
                                outer_repeat,
                            "outer_fold":
                                outer_fold,
                            "model":
                                model_enum.name,
                            "inner_MAE":
                                result["inner_mae"],
                            **self._config_columns(
                                result["configuration"]
                            ),
                        }
                    )

                # =============================================================
                # SELECT COMPLETE PIPELINE USING INNER CV ONLY
                # =============================================================

                selected = min(
                    family_results,
                    key=lambda item:
                    item["inner_mae"],
                )

                configuration = selected[
                    "configuration"
                ]

                logger.info(
                    "Outer repeat %d fold %d — "
                    "selected %s — inner MAE %.4f",
                    outer_repeat,
                    outer_fold,
                    configuration[
                        "model"
                    ].name,
                    selected[
                        "inner_mae"
                    ],
                )

                # =============================================================
                # FIT SELECTED PIPELINE ON ALL OUTER-TRAINING DATA
                # =============================================================

                (
                    predictions,
                    fit_time,
                    prediction_time,
                ) = self._fit_selected_pipeline(
                    signatures=signatures,
                    train_bags=train_bags,
                    test_bags=test_bags,
                    configuration=configuration,
                )

                # =============================================================
                # OUTER-TEST METRICS
                # =============================================================

                test_frame = self._select_bags(
                    signatures[
                        configuration[
                            "aggregation"
                        ]
                    ],
                    test_bags,
                )

                metrics = self._regression_metrics(
                    df=test_frame,
                    predictions=predictions,
                )

                # =============================================================
                # TRAINING-ONLY BASELINES
                # =============================================================

                (
                    mean_prediction,
                    median_prediction,
                ) = self._baseline_values(
                    df_train_reference
                )

                mean_predictions = np.full(
                    len(df_test_reference),
                    mean_prediction,
                    dtype=float,
                )

                median_predictions = np.full(
                    len(df_test_reference),
                    median_prediction,
                    dtype=float,
                )

                mean_metrics = (
                    self._regression_metrics(
                        df=df_test_reference,
                        predictions=(
                            mean_predictions
                        ),
                    )
                )

                median_metrics = (
                    self._regression_metrics(
                        df=df_test_reference,
                        predictions=(
                            median_predictions
                        ),
                    )
                )

                # =============================================================
                # STORE OUTER-FOLD RESULT
                # =============================================================

                outer_rows.append(
                    {
                        "outer_repeat":
                            outer_repeat,
                        "outer_fold":
                            outer_fold,

                        "selected_inner_MAE":
                            selected[
                                "inner_mae"
                            ],

                        **self._config_columns(
                            configuration
                        ),

                        "n_train_points":
                            df_train_reference[
                                self.schema.group
                            ].nunique(),

                        "n_test_points":
                            df_test_reference[
                                self.schema.group
                            ].nunique(),

                        "n_train_captures":
                            len(
                                df_train_reference
                            ),

                        "n_test_captures":
                            len(
                                df_test_reference
                            ),

                        "MAE":
                            metrics.mae,
                        "RMSE":
                            metrics.rmse,
                        "R2":
                            metrics.r2,

                        "mean_baseline_MAE":
                            mean_metrics.mae,
                        "mean_baseline_RMSE":
                            mean_metrics.rmse,
                        "mean_baseline_R2":
                            mean_metrics.r2,

                        "median_baseline_MAE":
                            median_metrics.mae,
                        "median_baseline_RMSE":
                            median_metrics.rmse,
                        "median_baseline_R2":
                            median_metrics.r2,

                        "fit_time":
                            fit_time,
                        "prediction_time":
                            prediction_time,
                    }
                )

                # =============================================================
                # STORE OUTER OOF PREDICTIONS
                # =============================================================

                prediction_rows.append(
                    self._oof_dataframe(
                        df_test=(
                            df_test_reference
                        ),
                        predictions=predictions,
                        mean_predictions=(
                            mean_predictions
                        ),
                        median_predictions=(
                            median_predictions
                        ),
                        configuration=(
                            configuration
                        ),
                        outer_repeat=(
                            outer_repeat
                        ),
                        outer_fold=(
                            outer_fold
                        ),
                    )
                )

        # =====================================================================
        # RESULTS
        # =====================================================================

        outer_results = pd.DataFrame(
            outer_rows
        )

        inner_candidates = pd.DataFrame(
            candidate_rows
        )

        oof_predictions = pd.concat(
            prediction_rows,
            ignore_index=True,
        )

        repeat_metrics = (
            self._repeat_metrics(
                oof_predictions
            )
        )

        summary = self._summarize_results(
            repeat_metrics
        )

        selection_frequency = (
            self._selection_frequency(
                outer_results
            )
        )

        # =====================================================================
        # FINAL CONFIGURATION
        # =====================================================================

        (
            final_selection,
            final_candidates,
        ) = self._select_final_configuration(
            signatures=signatures,
            reference=reference,
            feature_dimensions=(
                feature_dimensions
            ),
        )

        # =====================================================================
        # SAVE RAW EXPERIMENT OUTPUTS
        # =====================================================================

        self._save_results(
            outer_results=outer_results,
            inner_candidates=inner_candidates,
            oof_predictions=oof_predictions,
            repeat_metrics=repeat_metrics,
            summary=summary,
            selection_frequency=(
                selection_frequency
            ),
            final_selection=final_selection,
            final_candidates=final_candidates,
        )

    # =========================================================================
    # INNER SPLITS
    # =========================================================================

    def _make_inner_splits(
        self,
        df: pd.DataFrame,
        outer_repeat: int,
        outer_fold: int,
    ) -> list[InnerSplit]:
        """
        Create one fixed set of grouped inner folds.

        The exact same folds are used by all model families and trials.
        """

        inner_cv = GroupKFold(
            n_splits=self.inner_splits,
            shuffle=True,
            random_state=self._inner_seed(
                outer_repeat,
                outer_fold,
            ),
        )

        groups = df[
            self.schema.group
        ].to_numpy()

        splits = []

        for train_idx, validation_idx in (
            inner_cv.split(
                df,
                groups=groups,
            )
        ):

            splits.append(
                InnerSplit(
                    train_bags=tuple(
                        df.iloc[
                            train_idx
                        ][
                            self.schema.bag
                        ].tolist()
                    ),
                    validation_bags=tuple(
                        df.iloc[
                            validation_idx
                        ][
                            self.schema.bag
                        ].tolist()
                    ),
                )
            )

        return splits

    # =========================================================================
    # MODEL-FAMILY OPTIMIZATION
    # =========================================================================

    def _optimize_family(
        self,
        model_enum: RegressionModels,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
        train_bags: tuple,
        inner_splits: list[InnerSplit],
        feature_dimensions: dict[
            str,
            dict[str, int],
        ],
        min_inner_train_size: int,
        preprocessing_cache: dict,
        outer_repeat: int,
        outer_fold: int,
    ) -> dict:
        """
        Optimize one model family using inner grouped CV.
        """

        sampler = optuna.samplers.TPESampler(
            seed=self._optuna_seed(
                model_enum=model_enum,
                outer_repeat=outer_repeat,
                outer_fold=outer_fold,
            )
        )

        study = optuna.create_study(
            direction="minimize",
            sampler=sampler,
        )

        def objective(
            trial: optuna.Trial,
        ) -> float:

            configuration = (
                suggest_pipeline_configuration(
                    trial=trial,
                    model=model_enum,
                    feature_sets=(
                        self.feature_sets
                    ),
                    aggregations=(
                        self.aggregations
                    ),
                    reductions=(
                        self.reductions
                    ),
                    pca_indices_candidates=(
                        self.pca_indices_candidates
                    ),
                    pca_embeddings_candidates=(
                        self.pca_embeddings_candidates
                    ),
                    feature_dimensions=(
                        feature_dimensions
                    ),
                    min_inner_train_size=(
                        min_inner_train_size
                    ),
                )
            )

            trial.set_user_attr(
                "configuration",
                self._serializable_config(
                    configuration
                ),
            )

            try:

                return self._inner_cv_score(
                    signatures=signatures,
                    configuration=(
                        configuration
                    ),
                    inner_splits=(
                        inner_splits
                    ),
                    preprocessing_cache=(
                        preprocessing_cache
                    ),
                )

            except ModelConvergenceError as exc:

                trial.set_user_attr(
                    "convergence_failure",
                    str(exc),
                )

                raise optuna.TrialPruned(
                    str(exc)
                ) from exc

        study.optimize(
            objective,
            n_trials=self.optuna_trials,
            n_jobs=1,
            show_progress_bar=False,
        )

        completed = [
            trial
            for trial in study.trials
            if trial.state
            == optuna.trial.TrialState.COMPLETE
        ]

        if not completed:

            raise RuntimeError(
                f"{model_enum.name}: no completed "
                "Optuna trials."
            )

        stored = dict(
            study.best_trial.user_attrs[
                "configuration"
            ]
        )

        stored[
            "model"
        ] = model_enum

        logger.info(
            "%s — best inner MAE %.4f",
            model_enum.name,
            study.best_value,
        )

        return {
            "configuration":
                stored,
            "inner_mae":
                float(
                    study.best_value
                ),
        }

    # =========================================================================
    # INNER CV SCORE
    # =========================================================================

    def _inner_cv_score(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
        configuration: dict,
        inner_splits: list[InnerSplit],
        preprocessing_cache: dict,
    ) -> float:
        """
        Evaluate one complete configuration using pooled inner OOF
        predictions.
        """

        cache_key = (
            configuration[
                "aggregation"
            ],
            configuration[
                "feature_set"
            ],
            configuration[
                "reduction"
            ],
            configuration[
                "pca_indices_components"
            ],
            configuration[
                "pca_embeddings_components"
            ],
        )

        if cache_key not in preprocessing_cache:

            preprocessing_cache[
                cache_key
            ] = self._prepare_inner_folds(
                signatures=signatures,
                configuration=(
                    configuration
                ),
                inner_splits=(
                    inner_splits
                ),
            )

        prepared_folds = (
            preprocessing_cache[
                cache_key
            ]
        )

        prediction_frames = []

        for fold in prepared_folds:

            model = (
                ModelFactory.create_model(
                    configuration[
                        "model"
                    ],
                    params=configuration[
                        "model_params"
                    ],
                )
            )

            model.fit(
                fold.X_train,
                fold.y_train,
                sample_weight=(
                    fold.weights
                ),
            )

            y_pred, _ = model.predict(
                fold.X_validation
            )

            y_pred = (
                fold.processor
                .inverse_transform_target(
                    y_pred
                )
            )

            result = (
                fold.df_validation[
                    [
                        self.schema.group,
                        self.schema.bag,
                        self.schema.target,
                    ]
                ]
                .copy()
            )

            result[
                "prediction"
            ] = y_pred[
                self.schema.target
            ].to_numpy()

            prediction_frames.append(
                result
            )

        oof = pd.concat(
            prediction_frames,
            ignore_index=True,
        )

        metrics = self._regression_metrics(
            df=oof,
            predictions=oof[
                "prediction"
            ].to_numpy(),
        )

        return metrics.mae

    # =========================================================================
    # INNER PREPROCESSING
    # =========================================================================

    def _prepare_inner_folds(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
        configuration: dict,
        inner_splits: list[InnerSplit],
    ) -> list[PreparedInnerFold]:
        """
        Fit fold-specific preprocessing for one representation
        configuration.
        """

        df = signatures[
            configuration[
                "aggregation"
            ]
        ]

        prepared = []

        for split in inner_splits:

            df_train = self._select_bags(
                df,
                split.train_bags,
            )

            df_validation = (
                self._select_bags(
                    df,
                    split.validation_bags,
                )
            )

            X_train = df_train.drop(
                columns=[
                    self.schema.target
                ]
            )

            y_train = df_train[
                [
                    self.schema.target
                ]
            ]

            X_validation = (
                df_validation.drop(
                    columns=[
                        self.schema.target
                    ]
                )
            )

            processor = (
                PostSplitProcessor(
                    schema=self.schema,
                    feature_set=configuration[
                        "feature_set"
                    ],
                    reduction=configuration[
                        "reduction"
                    ],
                    pca_indices_components=(
                        configuration[
                            "pca_indices_components"
                        ]
                    ),
                    pca_embeddings_components=(
                        configuration[
                            "pca_embeddings_components"
                        ]
                    ),
                )
            )

            (
                X_train_processed,
                y_train_processed,
            ) = processor.fit_transform(
                X_train,
                y_train,
            )

            X_validation_processed = (
                processor.transform(
                    X_validation
                )
            )

            prepared.append(
                PreparedInnerFold(
                    df_validation=(
                        df_validation
                    ),
                    X_train=(
                        X_train_processed
                    ),
                    y_train=(
                        y_train_processed
                    ),
                    X_validation=(
                        X_validation_processed
                    ),
                    weights=(
                        self._point_weights(
                            df_train
                        )
                    ),
                    processor=processor,
                )
            )

        return prepared

    # =========================================================================
    # OUTER-FOLD FINAL FIT
    # =========================================================================

    def _fit_selected_pipeline(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
        train_bags: tuple,
        test_bags: tuple,
        configuration: dict,
    ) -> tuple[
        np.ndarray,
        float,
        float,
    ]:
        """
        Fit one selected complete pipeline on all outer-training data and
        predict the corresponding outer-test data.
        """

        df = signatures[
            configuration[
                "aggregation"
            ]
        ]

        df_train = self._select_bags(
            df,
            train_bags,
        )

        df_test = self._select_bags(
            df,
            test_bags,
        )

        X_train = df_train.drop(
            columns=[
                self.schema.target
            ]
        )

        y_train = df_train[
            [
                self.schema.target
            ]
        ]

        X_test = df_test.drop(
            columns=[
                self.schema.target
            ]
        )

        processor = PostSplitProcessor(
            schema=self.schema,
            feature_set=configuration[
                "feature_set"
            ],
            reduction=configuration[
                "reduction"
            ],
            pca_indices_components=(
                configuration[
                    "pca_indices_components"
                ]
            ),
            pca_embeddings_components=(
                configuration[
                    "pca_embeddings_components"
                ]
            ),
        )

        (
            X_train_processed,
            y_train_processed,
        ) = processor.fit_transform(
            X_train,
            y_train,
        )

        X_test_processed = (
            processor.transform(
                X_test
            )
        )

        model = ModelFactory.create_model(
            configuration[
                "model"
            ],
            params=configuration[
                "model_params"
            ],
        )

        fit_time = model.fit(
            X_train_processed,
            y_train_processed,
            sample_weight=(
                self._point_weights(
                    df_train
                )
            ),
        )

        (
            y_pred,
            prediction_time,
        ) = model.predict(
            X_test_processed
        )

        y_pred = (
            processor.inverse_transform_target(
                y_pred
            )
        )

        return (
            y_pred[
                self.schema.target
            ].to_numpy(),
            fit_time,
            prediction_time,
        )

    # =========================================================================
    # FINAL DEVELOPMENT-DATA SELECTION
    # =========================================================================

    def _select_final_configuration(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
        reference: pd.DataFrame,
        feature_dimensions: dict[
            str,
            dict[str, int],
        ],
    ) -> tuple[dict, pd.DataFrame]:
        """
        Select the final pipeline configuration using all development data.

        This selection is independent of the outer-CV scores.

        Outer CV estimates the performance of the selection procedure.
        This inner-CV search determines the configuration that should later
        be fitted to all available development data.
        """

        logger.info(
            "Selecting final pipeline on all development data"
        )

        all_bags = tuple(
            reference[
                self.schema.bag
            ].tolist()
        )

        inner_splits = (
            self._make_inner_splits(
                reference,
                outer_repeat=0,
                outer_fold=0,
            )
        )

        min_inner_train_size = min(
            len(
                split.train_bags
            )
            for split in inner_splits
        )

        preprocessing_cache = {}

        results = []

        rows = []

        for model_enum in self.models:

            result = self._optimize_family(
                model_enum=model_enum,
                signatures=signatures,
                train_bags=all_bags,
                inner_splits=inner_splits,
                feature_dimensions=(
                    feature_dimensions
                ),
                min_inner_train_size=(
                    min_inner_train_size
                ),
                preprocessing_cache=(
                    preprocessing_cache
                ),
                outer_repeat=0,
                outer_fold=0,
            )

            results.append(
                result
            )

            rows.append(
                {
                    "model":
                        model_enum.name,
                    "inner_MAE":
                        result[
                            "inner_mae"
                        ],
                    **self._config_columns(
                        result[
                            "configuration"
                        ]
                    ),
                }
            )

        selected = min(
            results,
            key=lambda item:
            item["inner_mae"],
        )

        configuration = (
            selected[
                "configuration"
            ]
        )

        final_selection = {
            "inner_MAE":
                selected[
                    "inner_mae"
                ],
            **self._config_columns(
                configuration
            ),
        }

        logger.info(
            "Final selected pipeline: %s — "
            "inner MAE %.4f",
            configuration[
                "model"
            ].name,
            selected[
                "inner_mae"
            ],
        )

        return (
            final_selection,
            pd.DataFrame(
                rows
            ),
        )

    # =========================================================================
    # BASELINES
    # =========================================================================

    def _baseline_values(
        self,
        df_train: pd.DataFrame,
    ) -> tuple[float, float]:
        """
        Calculate training-only Point-balanced constant baselines.

        Mean
            Weighted training mean.

        Median
            Weighted training median.

        The median baseline is especially relevant because MAE is the
        primary optimization metric.
        """

        y = df_train[
            self.schema.target
        ].to_numpy(
            dtype=float
        )

        weights = self._point_weights(
            df_train
        )

        mean_value = float(
            np.average(
                y,
                weights=weights,
            )
        )

        median_value = (
            self._weighted_median(
                values=y,
                weights=weights,
            )
        )

        return (
            mean_value,
            median_value,
        )

    @staticmethod
    def _weighted_median(
        values: np.ndarray,
        weights: np.ndarray,
    ) -> float:
        """
        Weighted median of a one-dimensional array.
        """

        order = np.argsort(
            values
        )

        values = values[
            order
        ]

        weights = weights[
            order
        ]

        cumulative = np.cumsum(
            weights
        )

        cutoff = (
            0.5
            * weights.sum()
        )

        index = np.searchsorted(
            cumulative,
            cutoff,
            side="left",
        )

        return float(
            values[
                index
            ]
        )

    # =========================================================================
    # POINT-BALANCED WEIGHTS
    # =========================================================================

    def _point_weights(
        self,
        df: pd.DataFrame,
    ) -> np.ndarray:
        """
        Give every physical Point the same total weight.

        CapturePointIds belonging to the same Point divide that Point's
        total weight among themselves.
        """

        n_captures = (
            df.groupby(
                self.schema.group
            )[self.schema.bag]
            .transform(
                "nunique"
            )
            .to_numpy()
        )

        weights = (
            1.0
            / n_captures
        )

        return (
            weights
            / weights.mean()
        )

    # =========================================================================
    # METRICS
    # =========================================================================

    def _regression_metrics(
        self,
        df: pd.DataFrame,
        predictions: np.ndarray,
    ) -> RegressionMetrics:
        """
        Calculate Point-balanced regression metrics.
        """

        observed = df[
            self.schema.target
        ].to_numpy(
            dtype=float
        )

        weights = self._point_weights(
            df
        )

        return RegressionMetrics(
            mae=mean_absolute_error(
                observed,
                predictions,
                sample_weight=weights,
            ),
            rmse=root_mean_squared_error(
                observed,
                predictions,
                sample_weight=weights,
            ),
            r2=r2_score(
                observed,
                predictions,
                sample_weight=weights,
            ),
        )

    # =========================================================================
    # OOF PREDICTIONS
    # =========================================================================

    def _oof_dataframe(
        self,
        df_test: pd.DataFrame,
        predictions: np.ndarray,
        mean_predictions: np.ndarray,
        median_predictions: np.ndarray,
        configuration: dict,
        outer_repeat: int,
        outer_fold: int,
    ) -> pd.DataFrame:
        """
        Store outer-test predictions for the selected pipeline and baselines.
        """

        result = df_test[
            [
                self.schema.group,
                self.schema.bag,
                self.schema.target,
            ]
        ].copy()

        result[
            "prediction"
        ] = predictions

        result[
            "mean_baseline_prediction"
        ] = mean_predictions

        result[
            "median_baseline_prediction"
        ] = median_predictions

        result[
            "outer_repeat"
        ] = outer_repeat

        result[
            "outer_fold"
        ] = outer_fold

        config = self._config_columns(
            configuration
        )

        for key, value in config.items():
            result[
                key
            ] = value

        return result

    # =========================================================================
    # REPEAT-LEVEL METRICS
    # =========================================================================

    def _repeat_metrics(
        self,
        oof_predictions: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Calculate one pooled OOF estimate per outer repeat.

        Predictions from different repeats are not treated as independent
        observations.
        """

        rows = []

        for repeat, df_repeat in (
            oof_predictions.groupby(
                "outer_repeat"
            )
        ):

            model_metrics = (
                self._regression_metrics(
                    df=df_repeat,
                    predictions=df_repeat[
                        "prediction"
                    ].to_numpy(),
                )
            )

            mean_metrics = (
                self._regression_metrics(
                    df=df_repeat,
                    predictions=df_repeat[
                        "mean_baseline_prediction"
                    ].to_numpy(),
                )
            )

            median_metrics = (
                self._regression_metrics(
                    df=df_repeat,
                    predictions=df_repeat[
                        "median_baseline_prediction"
                    ].to_numpy(),
                )
            )

            rows.append(
                {
                    "outer_repeat":
                        repeat,

                    "MAE":
                        model_metrics.mae,
                    "RMSE":
                        model_metrics.rmse,
                    "R2":
                        model_metrics.r2,

                    "mean_baseline_MAE":
                        mean_metrics.mae,
                    "mean_baseline_RMSE":
                        mean_metrics.rmse,
                    "mean_baseline_R2":
                        mean_metrics.r2,

                    "median_baseline_MAE":
                        median_metrics.mae,
                    "median_baseline_RMSE":
                        median_metrics.rmse,
                    "median_baseline_R2":
                        median_metrics.r2,
                }
            )

        return pd.DataFrame(
            rows
        )

    # =========================================================================
    # SUMMARY
    # =========================================================================

    @staticmethod
    def _summarize_results(
        repeat_metrics: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Summarize repeated outer-CV estimates.

        Repeats, rather than individual fold predictions, are used as the
        units for the reported mean and standard deviation.
        """

        metrics = [
            "MAE",
            "RMSE",
            "R2",
            "mean_baseline_MAE",
            "mean_baseline_RMSE",
            "mean_baseline_R2",
            "median_baseline_MAE",
            "median_baseline_RMSE",
            "median_baseline_R2",
        ]

        summary = {}

        for metric in metrics:

            summary[
                f"{metric}_mean"
            ] = (
                repeat_metrics[
                    metric
                ].mean()
            )

            summary[
                f"{metric}_std"
            ] = (
                repeat_metrics[
                    metric
                ].std()
            )

        return pd.DataFrame(
            [
                summary
            ]
        )

    # =========================================================================
    # SELECTION FREQUENCY
    # =========================================================================

    @staticmethod
    def _selection_frequency(
        outer_results: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Summarize how often major pipeline components were selected.

        This is a stability diagnostic, not a rule for choosing the final
        pipeline.
        """

        components = [
            "model",
            "feature_set",
            "aggregation",
            "reduction",
            "pca_indices_components",
            "pca_embeddings_components",
        ]

        rows = []

        total = len(
            outer_results
        )

        for component in components:

            counts = (
                outer_results[
                    component
                ]
                .value_counts(
                    dropna=False
                )
            )

            for value, count in counts.items():

                rows.append(
                    {
                        "component":
                            component,
                        "value":
                            value,
                        "count":
                            int(
                                count
                            ),
                        "fraction":
                            float(
                                count
                                / total
                            ),
                    }
                )

        return pd.DataFrame(
            rows
        )

    # =========================================================================
    # FEATURE DIMENSIONS
    # =========================================================================

    def _feature_dimensions(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
    ) -> dict[str, dict[str, int]]:
        """
        Determine feature dimensionality for each aggregation strategy.
        """

        dimensions = {}

        for aggregation in self.aggregations:

            df = signatures[
                aggregation
            ]

            index_dimension = len(
                self.schema.index_columns(
                    df.columns
                )
            )

            embedding_dimension = 0

            if (
                self.schema.embedding
                in df.columns
            ):

                embedding_dimension = len(
                    np.asarray(
                        df[
                            self.schema.embedding
                        ].iloc[0]
                    )
                )

            dimensions[
                aggregation
            ] = {
                "indices":
                    index_dimension,
                "embeddings":
                    embedding_dimension,
            }

        return dimensions

    # =========================================================================
    # SIGNATURE ALIGNMENT
    # =========================================================================

    def _check_signature_alignment(
        self,
        signatures: dict[
            str,
            pd.DataFrame,
        ],
    ) -> None:
        """
        Ensure all aggregation strategies describe the same CapturePointIds,
        Points and target values.

        This prevents different aggregation representations from being
        compared on different observations.
        """

        reference = (
            signatures[
                self.aggregations[0]
            ][
                [
                    self.schema.bag,
                    self.schema.group,
                    self.schema.target,
                ]
            ]
            .sort_values(
                self.schema.bag
            )
            .reset_index(
                drop=True
            )
        )

        for aggregation in self.aggregations[1:]:

            current = (
                signatures[
                    aggregation
                ][
                    [
                        self.schema.bag,
                        self.schema.group,
                        self.schema.target,
                    ]
                ]
                .sort_values(
                    self.schema.bag
                )
                .reset_index(
                    drop=True
                )
            )

            if not reference.equals(
                current
            ):

                raise ValueError(
                    "Aggregation representations do not "
                    "contain identical CapturePointIds, "
                    "Points and targets."
                )

    # =========================================================================
    # DATAFRAME HELPERS
    # =========================================================================

    def _select_bags(
        self,
        df: pd.DataFrame,
        bags: tuple,
    ) -> pd.DataFrame:
        """
        Select CapturePointIds while preserving dataframe row order.
        """

        bag_set = set(
            bags
        )

        return (
            df[
                df[
                    self.schema.bag
                ].isin(
                    bag_set
                )
            ]
            .copy()
        )

