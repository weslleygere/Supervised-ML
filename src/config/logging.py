    # =========================================================================
    # HELPERS
    # =========================================================================

    @staticmethod
    def _join_values(
        values,
    ) -> str:
        """
        Format configuration candidate values for the experiment log.
        """

        return ", ".join(
            str(
                value
            )
            for value in values
        )

    # =========================================================================
    # CLEANUP
    # =========================================================================

    def cleanup(
        self,
    ) -> None:
        """
        Close the experiment log and move it to the run output directory.
        """

        if not os.path.exists(
            LOG_PATH
        ):
            return

        try:

            root_logger = (
                logging.getLogger()
            )

            for handler in (
                root_logger.handlers[:]
            ):

                if isinstance(
                    handler,
                    logging.FileHandler,
                ):

                    handler.close()

                    root_logger.removeHandler(
                        handler
                    )

            shutil.move(
                LOG_PATH,
                os.path.join(
                    self.output_dir,
                    os.path.basename(
                        LOG_PATH
                    ),
                ),
            )

        except Exception as exc:

            logger.warning(
                "Could not move log file "
                "to output directory: %s",
                exc,
            )