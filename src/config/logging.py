import logging
import os
import platform
import shutil
from datetime import datetime
from logging import Filter

from .settings import Settings


logger = logging.getLogger(__name__)

LOG_PATH = "experiment.log"


class LogFilter(Filter):
    """
    Allow console logs generated by the project code.

    External-library logs are omitted from the console.
    """

    def filter(
        self,
        record: logging.LogRecord,
    ) -> bool:
        logger_name = record.name

        return (
            logger_name == "__main__"
            or logger_name.startswith("src.")
        )


class LogSetup:
    """
    Configure and manage logging for one experiment run.

    Parameters
    ----------
    settings : Settings
        Experiment configuration.
    """

    def __init__(
        self,
        settings: Settings,
    ) -> None:
        self.settings = settings

        self.log_level = (
            settings.logging.log_level.upper()
        )

        self.debug_mode = (
            settings.logging.debug
        )

        self.output_dir = (
            settings.data.output_dir
        )

    def setup_logging(self) -> None:
        """
        Configure file and console logging.
        """

        file_handler = logging.FileHandler(
            LOG_PATH,
            mode="a",
            encoding="utf-8",
        )

        file_handler.setLevel(
            logging.DEBUG
            if self.debug_mode
            else logging.INFO
        )

        console_handler = logging.StreamHandler()
        console_handler.setLevel(
            self.log_level
        )
        console_handler.addFilter(
            LogFilter()
        )

        formatter = logging.Formatter(
            "%(asctime)s | %(levelname)s | %(message)s"
        )

        file_handler.setFormatter(
            formatter
        )
        console_handler.setFormatter(
            formatter
        )

        logging.basicConfig(
            level=(
                logging.DEBUG
                if self.debug_mode
                else logging.INFO
            ),
            handlers=[
                file_handler,
                console_handler,
            ],
            force=True,
        )

        logging.captureWarnings(True)

    def write_log_metadata(self) -> None:
        """
        Write the main experiment configuration to the log.
        """

        model_names = ", ".join(
            model.name
            for model in self.settings.model.models
        )

        metadata = [
            "",
            "========== New Experiment ==========",
            f"Timestamp           : {datetime.now().isoformat()}",
            f"Output directory    : {self.output_dir}",
            f"Platform            : {platform.system()} {platform.release()}",
            f"Python version      : {platform.python_version()}",
            "",
            "---------- Data ----------",
            f"Dataset             : {self.settings.data.data_path}",
            f"Schema              : {self.settings.data.schema_path}",
            "",
            "---------- Representation ----------",
            f"Feature set         : {self.settings.model.feature_set}",
            f"PCA components      : {self.settings.model.pca_components}",
            "",
            "---------- Models ----------",
            f"Models              : {model_names}",
            f"Random state        : {self.settings.model.random_state}",
            "",
            "---------- Nested CV ----------",
            f"Outer folds         : {self.settings.validation.outer_splits}",
            f"Inner folds         : {self.settings.validation.inner_splits}",
            f"Optuna trials       : {self.settings.validation.optuna_trials}",
            "",
            "---------- Instance-MIR ----------",
            f"Inference k         : {self.settings.validation.inference_k}",
            f"Inference repeats   : {self.settings.validation.inference_repeats}",
            "",
        ]

        with open(
            LOG_PATH,
            "a",
            encoding="utf-8",
        ) as file:
            file.write(
                "\n".join(metadata)
            )

    def cleanup(self) -> None:
        """
        Close the experiment log and move it to the run output directory.
        """

        if not os.path.exists(LOG_PATH):
            return

        try:
            root_logger = logging.getLogger()

            for handler in root_logger.handlers[:]:
                if isinstance(
                    handler,
                    logging.FileHandler,
                ):
                    handler.close()
                    root_logger.removeHandler(
                        handler
                    )

            shutil.move(
                LOG_PATH,
                os.path.join(
                    self.output_dir,
                    os.path.basename(LOG_PATH),
                ),
            )

        except Exception as exc:
            logger.warning(
                "Could not move log file to output directory: %s",
                exc,
            )
