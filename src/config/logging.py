from logging import Filter

import optuna

from .settings import Settings


logger = logging.getLogger(__name__)

LOG_PATH = "experiment.log"


# =============================================================================
# LOG FILTER
# =============================================================================


class LogFilter(Filter):
    """
    Allow console logs generated by the project code.

    External-library logs are omitted from the console.
    """

    def filter(
        self,
        record: logging.LogRecord,
    ) -> bool:

        return (
            record.name == "__main__"
            or record.name.startswith("src.")
        )


# =============================================================================
# LOG SETUP
# =============================================================================


class LogSetup:
    """
    Configure and manage logging for one experiment run.
    """

    def __init__(
        self,
        settings: Settings,
    ) -> None:

        self.settings = settings

        self.log_level = (
            settings.logging.log_level.upper()
        )

        self.debug_mode = (
            settings.logging.debug
        )

        self.output_dir = (
            settings.data.output_dir
        )

    # =========================================================================
    # SETUP
    # =========================================================================

    def setup_logging(
        self,
    ) -> None:
        """
        Configure file and console logging.
        """

        file_handler = logging.FileHandler(
            LOG_PATH,
            mode="a",
            encoding="utf-8",
        )

        file_handler.setLevel(
            logging.DEBUG
            if self.debug_mode
            else logging.INFO
        )

        console_handler = (
            logging.StreamHandler()
        )

        console_handler.setLevel(
            self.log_level
        )

        console_handler.addFilter(
            LogFilter()
        )

        formatter = logging.Formatter(
            "%(asctime)s | %(levelname)s | %(message)s"
        )

        file_handler.setFormatter(
            formatter
        )

        console_handler.setFormatter(
            formatter
        )

        logging.basicConfig(
            level=(
                logging.DEBUG
                if self.debug_mode
                else logging.INFO
            ),
            handlers=[
                file_handler,
                console_handler,
            ],
            force=True,
        )

        logging.captureWarnings(
            True
        )

        optuna.logging.set_verbosity(
            optuna.logging.WARNING
        )

